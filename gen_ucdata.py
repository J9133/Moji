#!/usr/bin/env python3
"""Generates ucdata.h (Unicode blocks + character names) for unicode-viewer.c.
Needs: pip install fonttools   (only for the block table)"""
import re, sys, unicodedata
from fontTools.unicodedata import Blocks

SKIP_CATS = ("Cn", "Cs", "Co", "Cc")
ALGO_PREFIXES = ["CJK UNIFIED IDEOGRAPH-", "CJK COMPATIBILITY IDEOGRAPH-",
                 "TANGUT IDEOGRAPH-", "NUSHU CHARACTER-", "KHITAN SMALL SCRIPT CHARACTER-"]

GROUPS = ["Latin & Common", "Punctuation & Marks", "Symbols & Emoji", "Math & Technical",
          "European Scripts", "Middle Eastern Scripts", "East Asian Scripts", "Other Scripts"]
RULES = [  # first match wins
    (2, r"Emoticons|Pictograph|Transport|Dingbats|Miscellaneous Symbols|Enclosed (Alphanumeric Supplement|Ideographic)|"
        r"Playing Cards|Mahjong|Domino|Alchemical|Chess|Legacy Computing|Ornamental|Geometric Shapes Extended|Tags"),
    (3, r"Math|Arrows|Technical|Number Forms|Superscripts|Letterlike|Currency|Control Pictures|Optical|Box Drawing|"
        r"Block Elements|Geometric Shapes|Braille|Musical|Enclosed Alphanumerics|Symbols for|Counting|Duployan|Ancient Symbols"),
    (1, r"Punctuation|Diacritical|Spacing Modifier|Modifier Tone|Variation Selectors|Combining|Specials|Hanifi.*Marks"),
    (0, r"Latin|IPA|Phonetic|Basic|Alphabetic Presentation|Halfwidth and Fullwidth"),
    (5, r"Arabic|Hebrew|Syriac|Thaana|Samaritan|Mandaic|Nabataean|Palmyrene|Phoenician|Imperial Aramaic|Avestan|Parthian|"
        r"Pahlavi|Old (South|North) Arabian|Hatran|Elymaic|Sogdian|Manichaean|Rumi|Lydian|Lycian|Carian|Cuneiform|Egyptian|Anatolian"),
    (6, r"CJK|Hiragana|Katakana|Hangul|Bopomofo|Yi |Kangxi|Kanbun|Ideographic|Tangut|Nushu|Khitan|Kana|Lisu|Miao|Vertical Forms|Small Form|Enclosed CJK|Radicals"),
    (4, r"Greek|Cyrillic|Armenian|Georgian|Runic|Ogham|Glagolitic|Coptic|Gothic|Old Italic|Old Permic|Caucasian|Elbasan|Vithkuqi|Shavian|Deseret|Osage|Cypriot|Linear|Ogham"),
]
def group_of(name):
    for g, rx in RULES:
        if re.search(rx, name):
            return g
    return 7

# ---- blocks
rng, vals = Blocks.RANGES, Blocks.VALUES
blocks = []
for i, (s, n) in enumerate(zip(rng, vals)):
    e = (rng[i + 1] - 1) if i + 1 < len(rng) else 0x10FFFF
    if n == "No_Block":
        continue
    if not any(unicodedata.category(chr(c)) not in SKIP_CATS for c in range(s, e + 1)):
        continue
    blocks.append((s, e, n, group_of(n)))

# ---- names
names, algo = [], {}
for cp in range(0x110000):
    c = chr(cp)
    if unicodedata.category(c) in SKIP_CATS:
        continue
    n = unicodedata.name(c, "")
    if not n:
        continue
    if n.startswith("HANGUL SYLLABLE "):
        continue
    hit = next((p for p in ALGO_PREFIXES if n.startswith(p)), None)
    if hit:
        algo.setdefault(hit, []).append(cp)
        continue
    names.append((cp, n))

algo_ranges = []
for p, cps in algo.items():
    start = prev = cps[0]
    for cp in cps[1:] + [None]:
        if cp is None or cp != prev + 1:
            algo_ranges.append((start, prev, p))
            if cp is not None:
                start = cp
        prev = cp if cp is not None else prev

out = ["/* generated by gen_ucdata.py (Unicode %s) - do not edit */\n" % unicodedata.unidata_version,
       "#include <stdint.h>\n",
       "typedef struct { uint32_t start, end; const char *name; uint8_t group; } UBlock;\n",
       "static const char *const UC_GROUPS[] = {%s};\n" % ",".join('"%s"' % g.replace("&", "&") for g in GROUPS),
       "#define UC_NGROUPS %d\n" % len(GROUPS),
       "static const UBlock UC_BLOCKS[] = {\n"]
for s, e, n, g in blocks:
    out.append('  {0x%X,0x%X,"%s",%d},\n' % (s, e, n, g))
out.append("};\n#define UC_NBLOCKS %d\n" % len(blocks))
out.append("typedef struct { uint32_t start, end; const char *prefix; } UAlgo;\n")
out.append("static const UAlgo UC_ALGO[] = {\n")
for s, e, p in algo_ranges:
    out.append('  {0x%X,0x%X,"%s"},\n' % (s, e, p))
out.append("};\n#define UC_NALGO %d\n" % len(algo_ranges))

blob, offs, pos = [], [], 0
for cp, n in names:
    offs.append(pos)
    blob.append(n)
    pos += len(n) + 1
out.append("typedef struct { uint32_t cp, off; } UName;\n")
out.append("static const UName UC_NAMES[] = {\n")
line = []
for (cp, _n), o in zip(names, offs):
    line.append("{0x%X,%d}" % (cp, o))
    if len(line) == 8:
        out.append("  " + ",".join(line) + ",\n"); line = []
if line:
    out.append("  " + ",".join(line) + ",\n")
out.append("};\n#define UC_NNAMES %d\n" % len(names))
out.append("static const char UC_BLOB[] =\n")
chunk = []
for n in blob:
    chunk.append(n + "\\000")
    if len(chunk) == 12:
        out.append('  "' + "".join(chunk) + '"\n'); chunk = []
if chunk:
    out.append('  "' + "".join(chunk) + '"\n')
out.append(";\n")
open("ucdata.h", "w").write("".join(out))
print(len(blocks), "blocks,", len(names), "names,", len(algo_ranges), "algo ranges", file=sys.stderr)
